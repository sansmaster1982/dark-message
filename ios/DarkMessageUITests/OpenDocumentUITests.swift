import XCTest

/// Drives the real Decrypt screen on a simulator and proves that a document made
/// on Android arrives with its name intact and that Open actually puts the preview
/// on screen.
///
/// Written because the owner reported twice that a document sent from Android
/// decrypts on the iPhone but will not open, "as if the extension is lost", while
/// every unit test passed. The unit tests only ever called the helper functions;
/// they never tapped the button or asked the system to render anything. This one
/// does both.
final class OpenDocumentUITests: XCTestCase {

    /// A DOCUMENT payload framed exactly the way Android frames one:
    /// `[nameLen:2][name UTF-8][file bytes]`, encrypted with the passphrase below.
    ///
    /// The name is the real shape that failed on the owner's phone - a digit, a
    /// space, Cyrillic, parentheses and only then the extension - not a tidy
    /// ASCII sample. Generated by the Python reference implementation with a fixed
    /// salt and nonce, so this also proves the app reads that implementation byte
    /// for byte.
    private let payloadBase64 = """
        AQMAAQIDBAUGBwgJCgsMDQ4PZGVmZ2hpamtsbW5vsznslzM+1jzZmkcRHYU5Uk92rlv+2MucYRq1m8oR\
        uU48khuj8jTMg5XLXOVVWe39f+u7rh3dss7B1161tcI1DwsXMs1C65mIj2keix6X3TgM+pHfjpLxcOeN\
        Etj5aDGAcpeD3g4mzJwAhkC9kRyLwXf7GFAdgYzInpzCIZwRzCD5UbQtCIf8aFFWyMOyLQQo9UeIagwL\
        WLTtqMsn2DxBur3dxdhmxyq2U5ie63+0qLrli1vWY982SIWKvcLnt/+NwxETb91hXzRG/AZpTdiCziTf\
        8zATYucqTCzFcStUkfCtTf0=
        """

    private let passphrase = "ui-test-key"
    private let chatName = "UITest"
    private let documentName = "1 Ф9И7 (1).pdf"

    private var app: XCUIApplication!

    override func setUp() {
        continueAfterFailure = false
        app = XCUIApplication()
        app.launchArguments += ["-language", "en"]
        app.launch()
        dismissFirstRunScreens()
    }

    // MARK: - The whole path, from an empty app to a document on screen

    func testADocumentFromAndroidKeepsItsNameAndOpens() throws {
        createChat()
        goToDecryptTab()
        enterThePayload()
        chooseTheChat()
        tapDecrypt()

        // The card proves the decryption worked and the file was written.
        let card = app.staticTexts["Decrypted document:"]
        XCTAssertTrue(card.waitForExistence(timeout: 60),
                      "the document card never appeared; the screen says: \(visibleTexts())")

        // The owner's complaint, as an assertion: the name must still carry .pdf.
        XCTAssertTrue(app.staticTexts[documentName].exists,
                      "the document lost its name; the screen shows: \(visibleTexts())")

        // The point of the test.
        let open = app.buttons["Open"]
        XCTAssertTrue(open.waitForExistence(timeout: 5), "the Open button is missing")
        open.tap()

        // QLPreviewController puts its own Done button up. If the presentation was
        // dropped, or the system refused to render the file, nothing changes on
        // screen and this is what fails.
        let done = app.buttons["Done"]
        XCTAssertTrue(done.waitForExistence(timeout: 20),
                      "tapping Open changed nothing: the preview was never presented")

        done.tap()
        XCTAssertTrue(card.waitForExistence(timeout: 10), "closing the preview lost the result")
    }

    // MARK: - Steps

    /// Onboarding is four pages with a Skip, and the tutorial that follows is four
    /// more with Next and then Got it. Both have to be out of the way before
    /// anything on the chat list can be tapped.
    private func dismissFirstRunScreens() {
        let skip = app.buttons["Skip"]
        if skip.waitForExistence(timeout: 15) {
            skip.tap()
        }
        for _ in 0..<6 {
            let gotIt = app.buttons["Got it"]
            let next = app.buttons["Next"]
            if gotIt.waitForExistence(timeout: 3) {
                gotIt.tap()
                break
            } else if next.exists {
                next.tap()
            } else {
                break
            }
        }
        // The tutorial walks through the tabs and leaves the app on the last one it
        // pointed at, so come back to the chat list explicitly.
        let chats = app.tabBars.buttons["Chats"]
        XCTAssertTrue(chats.waitForExistence(timeout: 15),
                      "the tab bar never appeared\n\(hierarchy())")
        chats.tap()
        XCTAssertTrue(app.navigationBars["Dark Message"].waitForExistence(timeout: 15),
                      "the chat list never appeared\n\(hierarchy())")
    }

    private func createChat() {
        // The trailing toolbar button is the plus; the leading one opens the QR
        // scanner, which on a simulator has no camera.
        let bar = app.navigationBars["Dark Message"]
        let add = bar.buttons["plus"].exists
            ? bar.buttons["plus"]
            : bar.buttons.element(boundBy: max(bar.buttons.count - 1, 0))
        XCTAssertTrue(add.waitForExistence(timeout: 10), "no way to add a chat\n\(hierarchy())")
        add.tap()

        let name = app.textFields.firstMatch
        XCTAssertTrue(name.waitForExistence(timeout: 10),
                      "the new-chat sheet never opened\n\(hierarchy())")
        type(chatName, into: name, called: "contact name")

        // Reveal the passphrase before typing it. A SecureField cannot be read back,
        // and a key that half arrived looks exactly like a key that never saved -
        // the screen just says the chat has no passphrase.
        let eye = app.buttons["eye"]
        if eye.waitForExistence(timeout: 5) {
            eye.tap()
        }

        let pass = app.textFields.element(boundBy: 1).exists
            ? app.textFields.element(boundBy: 1)
            : app.secureTextFields.firstMatch
        XCTAssertTrue(pass.waitForExistence(timeout: 5), "no passphrase field\n\(hierarchy())")
        type(passphrase, into: pass, called: "passphrase")
        XCTAssertEqual(pass.value as? String, passphrase,
                       "the passphrase field did not take what was typed")

        let create = app.buttons["Create"]
        XCTAssertTrue(create.isEnabled, "Create is disabled, so the form is not filled in")
        create.tap()
        XCTAssertTrue(app.staticTexts[chatName].waitForExistence(timeout: 10), "the chat was not created")
    }

    private func goToDecryptTab() {
        app.tabBars.buttons["Decrypt"].tap()
        XCTAssertTrue(app.navigationBars["Decrypt"].waitForExistence(timeout: 10), "the Decrypt tab did not open")
    }

    /// Typed rather than pasted: reading the pasteboard raises the system paste
    /// prompt, which would make the test about that alert instead of about Open.
    private func enterThePayload() {
        let editor = app.textViews.firstMatch
        XCTAssertTrue(editor.waitForExistence(timeout: 10), "the paste field is missing")
        let text = payloadBase64.replacingOccurrences(of: "\n", with: "")
        type(text, into: editor, called: "payload field")

        // Typing hundreds of characters into a TextEditor can drop some, and a
        // base64 payload one character short only ever says "wrong passphrase".
        let typed = (editor.value as? String) ?? ""
        XCTAssertEqual(typed.count, text.count,
                       "the field did not take the whole payload (\(typed.count) of \(text.count))")
    }

    /// Taps a field, waits for the keyboard to actually take focus, and only then types.
    ///
    /// `tap()` returns as soon as the touch is delivered, not when the field has become
    /// first responder, so typing immediately after it is a race. When it is lost
    /// XCUITest fails with "Neither element nor any descendant has keyboard focus" -
    /// which is what happened on run 35256018034 while the identical test had passed
    /// ten minutes earlier. A flaky test is worse than no test: it teaches you to
    /// ignore a red build.
    private func type(_ text: String, into field: XCUIElement, called name: String,
                      file: StaticString = #filePath, line: UInt = #line) {
        for attempt in 1...2 {
            field.tap()
            // The keyboard appearing is the observable proof that some field took focus.
            if app.keyboards.element.waitForExistence(timeout: 10) {
                field.typeText(text)
                return
            }
            if attempt == 1 {
                // Something else may hold focus - dismiss and come back to it.
                if app.toolbars.buttons.count > 0 {
                    app.toolbars.buttons.firstMatch.tap()
                }
            }
        }
        XCTFail("the keyboard never appeared for the \(name)\n\(hierarchy())", file: file, line: line)
    }

    private func chooseTheChat() {
        // The selector is a Menu whose label reads "Dark Message" until a chat is
        // picked. Dismiss the keyboard first so it cannot cover the menu.
        if app.keyboards.count > 0 {
            app.toolbars.buttons.firstMatch.tap()
        }
        let picker = app.buttons["Dark Message"]
        if picker.waitForExistence(timeout: 5) {
            picker.tap()
            let entry = app.buttons[chatName]
            XCTAssertTrue(entry.waitForExistence(timeout: 5),
                          "the chat menu did not open\n\(hierarchy())")
            entry.tap()
        }
        // Decrypt stays disabled until a chat is chosen, and a disabled button
        // swallows the tap silently. Once picked, the selector shows the chat name
        // as its label rather than "Dark Message".
        XCTAssertTrue(app.staticTexts[chatName].waitForExistence(timeout: 5),
                      "no chat is selected; the screen says: \(visibleTexts())")
    }

    /// There are two buttons called "Decrypt": the tab at the bottom and the action.
    /// firstMatch picks the tab, whose tap does nothing at all because that tab is
    /// already open - which looks exactly like a decryption that silently failed.
    private func tapDecrypt() {
        XCTAssertTrue(app.buttons["Decrypt"].firstMatch.waitForExistence(timeout: 10),
                      "the Decrypt button is missing")
        let all = app.buttons.matching(identifier: "Decrypt").allElementsBoundByIndex
        let action = all.first { $0.frame.width > app.frame.width * 0.5 } ?? all.last
        XCTAssertNotNil(action, "no full-width Decrypt button\n\(hierarchy())")
        action?.tap()
    }

    /// Everything readable on screen, so a failure message says what went wrong
    /// instead of only that an element was missing.
    private func visibleTexts() -> String {
        app.staticTexts.allElementsBoundByIndex
            .prefix(20)
            .map { $0.label }
            .filter { !$0.isEmpty }
            .joined(separator: " | ")
    }

    /// The whole element tree, trimmed. A UI test that fails on a CI machine you
    /// cannot look at is worthless without this.
    private func hierarchy() -> String {
        String(app.debugDescription.prefix(4000))
    }
}
